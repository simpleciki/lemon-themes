// Every word the plugin shows, in Chinese and English. The /skin pane switches between them; a new
// install starts in the system's language (LANG). Skin-specific words live in each skin's skin.ts.

export type Lang = 'zh' | 'en'
/** A piece of text in both languages. */
export type L = { zh: string; en: string }

export const pick = (l: L, lang: Lang) => l[lang]

export function langFromEnv(value: string | undefined): Lang {
  return value !== undefined && /^zh/i.test(value) ? 'zh' : 'en'
}

